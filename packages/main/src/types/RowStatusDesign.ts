/**
 * Defines the rendering design of the row status indicator.
 *
 * @private
 */
enum RowStatusDesign {
	/**
	 * Renders only the status bar.
	 * @private
	 */
	Simple = "Simple",

	/**
	 * Renders the status bar together with an icon.
	 * @private
	 */
	Extended = "Extended",
}

export default RowStatusDesign;
