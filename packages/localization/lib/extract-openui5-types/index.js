/**
 * Pre-tsc step: reads @types/openui5 and writes src/openui5-types.d.ts with all
 * sap/ ambient module declarations renamed to @ui5/openui5-types/sap/... prefix.
 *
 * This file is referenced via tsconfig paths so tsc can resolve
 * `import type X from "@ui5/openui5-types/sap/..."` during compilation.
 * It is gitignored — generated as part of the build.
 *
 * The @ui5/openui5-types/ prefix prevents conflicts with @types/openui5
 * when both are present in a consumer's project.
 */

import ts from "typescript";
import fs from "fs/promises";
import path from "path";
import { createRequire } from "module";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

const SRC_DIR = path.resolve(__dirname, "../../src");
const DIST_DIR = path.resolve(__dirname, "../../dist");
const SRC_OUT = path.join(SRC_DIR, "openui5-types.d.ts");
const DIST_OUT = path.join(DIST_DIR, "openui5-types.d.ts");
const OPENUI5_TYPES = require.resolve("@types/openui5/sap.ui.core.d.ts");
const MODULE_PREFIX = "@ui5/openui5-types/";

const generate = async () => {
	const source = await fs.readFile(OPENUI5_TYPES, "utf-8");
	const sourceFile = ts.createSourceFile(OPENUI5_TYPES, source, ts.ScriptTarget.Latest, true);
	const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });

	const blocks = [];
	ts.forEachChild(sourceFile, node => {
		if (
			ts.isModuleDeclaration(node) &&
			ts.isStringLiteral(node.name) &&
			node.name.text.startsWith("sap/")
		) {
			let text = printer.printNode(ts.EmitHint.Unspecified, node, sourceFile);
			text = text.replace(
				`declare module "${node.name.text}"`,
				`declare module "${MODULE_PREFIX}${node.name.text}"`
			);
			// Rename all internal sap/ references in import/export statements
			text = text.replace(/from "sap\//g, `from "${MODULE_PREFIX}sap/`);
			text = text.replace(/from 'sap\//g, `from '${MODULE_PREFIX}sap/`);
			blocks.push(text);
		}
	});

	const content = [
		"// Auto-generated by extract-openui5-types. Do not edit.",
		"// All sap/ module declarations from @types/openui5, prefixed with @ui5/openui5-types/.",
		"// Gitignored — regenerated on every build.",
		"",
		...blocks,
		"",
	].join("\n");

	await fs.writeFile(SRC_OUT, content, "utf-8");
	await fs.mkdir(DIST_DIR, { recursive: true });
	await fs.writeFile(DIST_OUT, content, "utf-8");
	console.log(`extract-openui5-types: wrote ${blocks.length} module declarations to src/openui5-types.d.ts and dist/openui5-types.d.ts`);
};

generate().catch(err => { console.error(err); process.exit(1); });
