import "@ui5/webcomponents/dist/Table.js";
import "@ui5/webcomponents/dist/TableHeaderRow.js";
import "@ui5/webcomponents/dist/TableHeaderCell.js";
import "@ui5/webcomponents/dist/TableHeaderCellActionAI.js";
import "@ui5/webcomponents/dist/TableRow.js";
import "@ui5/webcomponents/dist/TableCell.js";
import "@ui5/webcomponents/dist/Text.js";
import "@ui5/webcomponents/dist/Toast.js";
import "@ui5/webcomponents/dist/Menu.js";
import "@ui5/webcomponents/dist/MenuItem.js";
import "@ui5/webcomponents-icons/dist/sort-ascending.js";
import "@ui5/webcomponents-icons/dist/sort-descending.js";

const table = document.getElementById("table");
const menu = document.getElementById("sortMenu");
const toast = document.getElementById("message");

const fieldByColumn = {
	productCol: "product",
	supplierCol: "supplier",
};

let activeColumn = null;

// Open the sorting menu when an interactive column header is activated.
table.querySelectorAll("ui5-table-header-cell[interactive]").forEach((headerCell) => {
	headerCell.addEventListener("header-click", (e) => {
		activeColumn = e.currentTarget;
		menu.opener = activeColumn;
		menu.open = true;
	});
});

// Apply the chosen sort order to the active column.
menu.addEventListener("item-click", (e) => {
	const sortOrder = e.detail.item.icon === "sort-ascending" ? "Ascending" : "Descending";

	// Display the sort indicator icon only on the active column.
	table.querySelectorAll("ui5-table-header-cell[interactive]").forEach((headerCell) => {
		headerCell.sortIndicator = headerCell === activeColumn ? sortOrder : "None";
	});

	// Reorder the rows based on the selected column and direction.
	const field = fieldByColumn[activeColumn.id];
	const rows = [...table.querySelectorAll("ui5-table-row")];
	rows.sort((rowA, rowB) => {
		const result = rowA.dataset[field].localeCompare(rowB.dataset[field]);
		return sortOrder === "Ascending" ? result : -result;
	});
	rows.forEach((row) => table.appendChild(row));
});

// The "Generated by AI" action is a separate control inside the header. Clicking it shows a
// message and does not fire the header's `header-click` event (so the sort menu stays closed).
document.getElementById("supplierAI").addEventListener("click", () => {
	toast.textContent = "This column was generated by AI";
	toast.open = true;
});
