import { useRef, useState } from "react";
import createReactComponent from "@ui5/webcomponents-base/dist/createReactComponent.js";
import { type UI5CustomEvent } from "@ui5/webcomponents-base";
import TableClass from "@ui5/webcomponents/dist/Table.js";
import TableCellClass from "@ui5/webcomponents/dist/TableCell.js";
import TableHeaderCellClass from "@ui5/webcomponents/dist/TableHeaderCell.js";
import TableHeaderCellActionAIClass from "@ui5/webcomponents/dist/TableHeaderCellActionAI.js";
import TableHeaderRowClass from "@ui5/webcomponents/dist/TableHeaderRow.js";
import TableRowClass from "@ui5/webcomponents/dist/TableRow.js";
import TextClass from "@ui5/webcomponents/dist/Text.js";
import ToastClass from "@ui5/webcomponents/dist/Toast.js";
import MenuClass from "@ui5/webcomponents/dist/Menu.js";
import MenuItemClass from "@ui5/webcomponents/dist/MenuItem.js";
import "@ui5/webcomponents-icons/dist/sort-ascending.js";
import "@ui5/webcomponents-icons/dist/sort-descending.js";

const Table = createReactComponent(TableClass);
const TableCell = createReactComponent(TableCellClass);
const TableHeaderCell = createReactComponent(TableHeaderCellClass);
const TableHeaderCellActionAI = createReactComponent(TableHeaderCellActionAIClass);
const TableHeaderRow = createReactComponent(TableHeaderRowClass);
const TableRow = createReactComponent(TableRowClass);
const Text = createReactComponent(TextClass);
const Toast = createReactComponent(ToastClass);
const Menu = createReactComponent(MenuClass);
const MenuItem = createReactComponent(MenuItemClass);

type Row = { key: string; product: string; sku: string; supplier: string; dimensions: string; price: number };
type SortField = "product" | "supplier";
type SortOrder = "None" | "Ascending" | "Descending";

const rows: Row[] = [
	{ key: "a", product: "Notebook Basic 15", sku: "HT-1000", supplier: "Very Best Screens", dimensions: "30 x 18 x 3 cm", price: 956 },
	{ key: "b", product: "Notebook Basic 17", sku: "HT-1001", supplier: "Smartcards", dimensions: "29 x 17 x 3.1 cm", price: 1249 },
	{ key: "c", product: "Notebook Basic 18", sku: "HT-1002", supplier: "Technocom", dimensions: "32 x 21 x 4 cm", price: 29 },
];

const fieldByColumn: Record<string, SortField> = {
  productCol: "product",
  supplierCol: "supplier",
};

function App() {
  const toastRef = useRef<ToastClass>(null);
  const [menuOpen, setMenuOpen] = useState(false);
  const [activeColumn, setActiveColumn] = useState("");
  const [sortField, setSortField] = useState<SortField | undefined>(undefined);
  const [sortOrder, setSortOrder] = useState<SortOrder>("None");

  const handleHeaderClick = (e: UI5CustomEvent<TableHeaderCellClass, "header-click">) => {
    setActiveColumn(e.currentTarget.id);
    setMenuOpen(true);
  };

  const handleSort = (e: UI5CustomEvent<MenuClass, "item-click">) => {
    setSortField(fieldByColumn[activeColumn]);
    setSortOrder(e.detail.item.icon === "sort-ascending" ? "Ascending" : "Descending");
    setMenuOpen(false);
  };

  // The "Generated by AI" action is a separate control inside the header. Clicking it shows a
  // message and does not fire the header's `header-click` event (so the sort menu stays closed).
  const handleAIClick = () => {
    if (toastRef.current) {
      toastRef.current.textContent = "This column was generated by AI";
      toastRef.current.open = true;
    }
  };

  const sortedRows = [...rows];
  if (sortField && sortOrder !== "None") {
    sortedRows.sort((a, b) => {
      const result = a[sortField].localeCompare(b[sortField]);
      return sortOrder === "Ascending" ? result : -result;
    });
  }

  const sortIndicatorFor = (field: SortField): SortOrder => (sortField === field ? sortOrder : "None");

  return (
    <>
      <Toast ref={toastRef} id="message" />
      <Table id="table">
        <TableHeaderRow slot="headerRow">
          <TableHeaderCell
            id="productCol"
            interactive
            aria-haspopup="menu"
            sortIndicator={sortIndicatorFor("product")}
            onHeaderClick={handleHeaderClick}
          >
            <span>Product</span>
          </TableHeaderCell>
          <TableHeaderCell
            id="supplierCol"
            interactive
            aria-haspopup="menu"
            sortIndicator={sortIndicatorFor("supplier")}
            onHeaderClick={handleHeaderClick}
          >
            <span>Supplier</span>
            <TableHeaderCellActionAI slot="action" onClick={handleAIClick} />
          </TableHeaderCell>
          {/* playground-fold */}
          <TableHeaderCell id="dimensionsCol">Dimensions</TableHeaderCell>
          <TableHeaderCell id="priceCol"><span>Price</span></TableHeaderCell>
          {/* playground-fold-end */}
        </TableHeaderRow>
        {sortedRows.map((row) => (
          <TableRow key={row.key} rowKey={row.key}>
            <TableCell>
              <Text>
                <b>{row.product}</b>
                <br />
                {row.sku}
              </Text>
            </TableCell>
            {/* playground-fold */}
            <TableCell><Text>{row.supplier}</Text></TableCell>
            <TableCell><Text>{row.dimensions}</Text></TableCell>
            <TableCell><Text><b>{row.price}</b> EUR</Text></TableCell>
            {/* playground-fold-end */}
          </TableRow>
        ))}
      </Table>
      <Menu
        open={menuOpen}
        opener={activeColumn}
        onItemClick={handleSort}
        onClose={() => setMenuOpen(false)}
      >
        <MenuItem icon="sort-ascending" text="Sort Ascending" />
        <MenuItem icon="sort-descending" text="Sort Descending" />
      </Menu>
    </>
  );
}

export default App;
