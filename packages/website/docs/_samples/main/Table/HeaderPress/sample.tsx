import { useRef } from "react";
import createReactComponent from "@ui5/webcomponents-base/dist/createReactComponent.js";
import { type UI5CustomEvent } from "@ui5/webcomponents-base";
import TableClass from "@ui5/webcomponents/dist/Table.js";
import TableCellClass from "@ui5/webcomponents/dist/TableCell.js";
import TableHeaderCellClass from "@ui5/webcomponents/dist/TableHeaderCell.js";
import TableHeaderCellActionAIClass from "@ui5/webcomponents/dist/TableHeaderCellActionAI.js";
import TableHeaderRowClass from "@ui5/webcomponents/dist/TableHeaderRow.js";
import TableRowClass from "@ui5/webcomponents/dist/TableRow.js";
import TextClass from "@ui5/webcomponents/dist/Text.js";
import ToastClass from "@ui5/webcomponents/dist/Toast.js";

const Table = createReactComponent(TableClass);
const TableCell = createReactComponent(TableCellClass);
const TableHeaderCell = createReactComponent(TableHeaderCellClass);
const TableHeaderCellActionAI = createReactComponent(TableHeaderCellActionAIClass);
const TableHeaderRow = createReactComponent(TableHeaderRowClass);
const TableRow = createReactComponent(TableRowClass);
const Text = createReactComponent(TextClass);
const Toast = createReactComponent(ToastClass);

type Row = { key: string; product: string; sku: string; supplier: string; dimensions: string; price: number };

const rows: Row[] = [
	{ key: "a", product: "Notebook Basic 15", sku: "HT-1000", supplier: "Very Best Screens", dimensions: "30 x 18 x 3 cm", price: 956 },
	{ key: "b", product: "Notebook Basic 17", sku: "HT-1001", supplier: "Smartcards", dimensions: "29 x 17 x 3.1 cm", price: 1249 },
	{ key: "c", product: "Notebook Basic 18", sku: "HT-1002", supplier: "Technocom", dimensions: "32 x 21 x 4 cm", price: 29 },
];

function App() {
  const toastRef = useRef<ToastClass>(null);

  const handleHeaderPress = (e: UI5CustomEvent<TableHeaderCellClass, "header-press">) => {
    if (toastRef.current) {
      const headerText = e.currentTarget.textContent?.trim();
      toastRef.current.textContent = `Column header ${headerText} pressed`;
      toastRef.current.open = true;
    }
  };

  const handleAIClick = () => {
    if (toastRef.current) {
      toastRef.current.textContent = "This column was generated by AI";
      toastRef.current.open = true;
    }
  };

  return (
    <>
      <Toast ref={toastRef} id="message" />
      <Table id="table">
        <TableHeaderRow slot="headerRow">
          <TableHeaderCell
            id="productCol"
            interactive
            onHeaderPress={handleHeaderPress}
          >
            <span>Product</span>
          </TableHeaderCell>
          {/* playground-fold */}
          <TableHeaderCell id="supplierCol" interactive onHeaderPress={handleHeaderPress}>
            <span>Supplier</span>
            <TableHeaderCellActionAI slot="action" onClick={handleAIClick} />
          </TableHeaderCell>
          <TableHeaderCell id="dimensionsCol">Dimensions</TableHeaderCell>
          {/* playground-fold-end */}
          <TableHeaderCell
            id="priceCol"
            interactive
            onHeaderPress={handleHeaderPress}
          >
            <span>Price</span>
          </TableHeaderCell>
        </TableHeaderRow>
        {rows.map((row) => (
          <TableRow key={row.key} rowKey={row.key}>
            <TableCell>
              <Text>
                <b>{row.product}</b>
                <br />
                {row.sku}
              </Text>
            </TableCell>
            {/* playground-fold */}
            <TableCell><Text>{row.supplier}</Text></TableCell>
            <TableCell><Text>{row.dimensions}</Text></TableCell>
            {/* playground-fold-end */}
            <TableCell>
              <Text>
                <b>{row.price}</b> EUR
              </Text>
            </TableCell>
          </TableRow>
        ))}
      </Table>
    </>
  );
}

export default App;
